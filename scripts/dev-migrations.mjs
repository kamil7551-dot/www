/* global URL, process, console */
// Writes apps/worker/src/dev/migrations.ts from migrations/*.sql, so the dev Durable Object
// applies the same migrations as D1. `--check` fails when the file is out of date (run in CI).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../migrations/", import.meta.url);
const out = new URL("../apps/worker/src/dev/migrations.ts", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = `// Generated by scripts/dev-migrations.mjs from migrations/*.sql. Do not edit.
export const MIGRATIONS: { name: string; sql: string }[] = [
${files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(new URL(f, dir), "utf8"))} },`).join("\n")}
];
`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    // missing file: treated as out of date
  }
  if (current !== body) {
    console.error("apps/worker/src/dev/migrations.ts is out of date. Run: node scripts/dev-migrations.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(out, body);
}
